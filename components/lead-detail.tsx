import Link from "next/link";
import { ArrowLeft, Check, ExternalLink, Sparkles, TriangleAlert } from "lucide-react";

import { AnalyzeLeadButton } from "@/components/analyze-lead-button";
import { EmptyState } from "@/components/empty-state";
import { Badge } from "@/components/ui/badge";
import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";
import {
  fitLabelTone,
  formatConfidence,
  splitSignals,
} from "@/lib/analysis-display";
import { formatDateTime, scoreTone, titleCase } from "@/lib/format";
import type { Company, LeadAnalysis, LeadStatus, SearchCriteria } from "@/types";

/** Tone → bar colour, kept as full class names so Tailwind emits them. */
const SCORE_BAR: Record<ReturnType<typeof scoreTone>, string> = {
  high: "bg-success",
  medium: "bg-warning",
  low: "bg-muted-foreground/50",
};

const ANALYSIS_NOTICE =
  "Generated by AI from the provider data above. Inferences are not independently verified, and nothing here was looked up outside the supplied fields.";

interface LeadDetailProps {
  company: Company;
  analysis: LeadAnalysis | null;
  status: LeadStatus;
  analyzedAt: string | null;
  /** Search context, when the user arrived from a search. */
  criteria?: SearchCriteria;
  /** False when ANTHROPIC_API_KEY is absent. */
  aiConfigured: boolean;
}

/**
 * A server component: it renders stored rows only. The analysis panel is kept
 * in place so the layout is unchanged when Phase 4 starts writing AI output —
 * until then every lead renders the "not analyzed yet" state.
 */
export function LeadDetail({
  company,
  analysis,
  status,
  analyzedAt,
  criteria,
  aiConfigured,
}: LeadDetailProps) {
  return (
    <div className="space-y-6">
      <div>
        <Link
          href="/leads"
          className="inline-flex items-center gap-1.5 text-sm text-muted-foreground hover:text-foreground"
        >
          <ArrowLeft className="size-4" aria-hidden="true" />
          Back to leads
        </Link>
      </div>

      {/* Identity */}
      <div className="flex flex-col gap-4 sm:flex-row sm:items-start sm:justify-between">
        <div className="min-w-0 space-y-2">
          <div className="flex flex-wrap items-center gap-2">
            <h1 className="text-2xl font-semibold tracking-tight break-words">
              {company.name}
            </h1>
            <Badge variant="outline">{statusLabel(status)}</Badge>
          </div>
          {company.website ? (
            <a
              href={company.website}
              target="_blank"
              rel="noreferrer noopener"
              className="inline-flex max-w-full items-center gap-1.5 text-sm text-primary hover:underline"
            >
              <span className="break-all">{company.domain ?? company.website}</span>
              <ExternalLink className="size-3.5 shrink-0" aria-hidden="true" />
            </a>
          ) : (
            <p className="text-sm text-muted-foreground">No website on file</p>
          )}
        </div>

        <AnalyzeLeadButton
          companyId={company.id}
          analyzed={analysis !== null}
          aiConfigured={aiConfigured}
        />
      </div>

      {criteria ? (
        <p className="text-sm text-muted-foreground">
          From your search: {criteria.industry} · {criteria.location} ·{" "}
          {criteria.companySize} employees
        </p>
      ) : null}

      <div className="grid gap-6 lg:grid-cols-3">
        {/* Company information — known facts only */}
        <Card className="lg:col-span-2">
          <CardHeader>
            <div className="flex flex-wrap items-center gap-2">
              <CardTitle>Company information</CardTitle>
              <Badge variant="outline">Provider data</Badge>
            </div>
            <CardDescription>
              Reported by the lead data provider. Not verified by LeadFlow.
            </CardDescription>
          </CardHeader>
          <CardContent>
            <dl className="grid gap-x-6 gap-y-4 sm:grid-cols-2">
              <Fact label="Industry" value={company.industry} />
              <Fact label="Location" value={company.location} />
              <Fact
                label="Company size"
                value={
                  company.employeeCount === null
                    ? null
                    : `${company.employeeCount} employees`
                }
              />
              <Fact label="Domain" value={company.domain} />
              <Fact label="Provider ID" value={company.providerId} mono />
            </dl>
          </CardContent>
        </Card>

        {/* Contact */}
        <Card>
          <CardHeader>
            <div className="flex flex-wrap items-center gap-2">
              <CardTitle>Contact</CardTitle>
              <Badge variant="outline">Provider data</Badge>
            </div>
          </CardHeader>
          <CardContent className="space-y-4">
            <Fact label="Name" value={company.contactName} />
            <Fact label="Email" value={company.contactEmail} />
            <div>
              <dt className="text-xs font-medium tracking-wide text-muted-foreground uppercase">
                Email status
              </dt>
              <dd className="mt-1">
                {company.emailStatus === "not_found" ? (
                  <span className="text-sm text-muted-foreground">
                    No email on file
                  </span>
                ) : (
                  <Badge
                    variant={
                      company.emailStatus === "verified" ? "success" : "warning"
                    }
                  >
                    {titleCase(company.emailStatus)}
                  </Badge>
                )}
              </dd>
            </div>
          </CardContent>
        </Card>
      </div>

      {/* AI analysis — inference, clearly separated from the facts above */}
      <Card>
        <CardHeader>
          <div className="flex flex-wrap items-center gap-2">
            <CardTitle>AI analysis</CardTitle>
            <Badge variant="info">AI inference</Badge>
          </div>
          <CardDescription>
            Generated from the provider data above. Inferences are not
            independently verified.
            {analyzedAt ? ` Last analyzed ${formatDateTime(analyzedAt)}.` : ""}
          </CardDescription>
        </CardHeader>

        <CardContent>
          {analysis ? (
            <AnalysisResult analysis={analysis} />
          ) : (
            <EmptyState
              icon={Sparkles}
              title="This lead has not been analyzed yet"
              description={
                aiConfigured
                  ? "Select Analyze lead to score this company against your search criteria and get a recommended next step. Analysis runs only when you ask for it."
                  : "Analysis needs an Anthropic API key. Add ANTHROPIC_API_KEY to your environment and restart the app."
              }
            />
          )}
        </CardContent>
      </Card>
    </div>
  );
}

function statusLabel(status: LeadStatus) {
  if (status === "analyzed") return "Analyzed";
  if (status === "saved") return "Saved";
  return "Not analyzed";
}

function Fact({
  label,
  value,
  mono = false,
}: {
  label: string;
  value: string | null;
  mono?: boolean;
}) {
  return (
    <div className="min-w-0">
      <dt className="text-xs font-medium tracking-wide text-muted-foreground uppercase">
        {label}
      </dt>
      <dd
        className={`mt-1 text-sm break-words ${mono ? "font-mono text-xs break-all" : ""} ${
          value ? "" : "text-muted-foreground"
        }`}
      >
        {value ?? "Not available"}
      </dd>
    </div>
  );
}

function AnalysisResult({ analysis }: { analysis: LeadAnalysis }) {
  const tone = scoreTone(analysis.fitScore);
  const { evidence, inferred } = splitSignals(analysis.signals);

  return (
    <div className="space-y-6">
      <div className="grid gap-6 sm:grid-cols-2">
        <div>
          <p className="text-xs font-medium tracking-wide text-muted-foreground uppercase">
            Fit score
          </p>
          <div className="mt-1 flex flex-wrap items-baseline gap-x-2 gap-y-1">
            <span className="text-3xl font-semibold tabular-nums">
              {analysis.fitScore}
            </span>
            <span className="text-sm text-muted-foreground">/100</span>
            <Badge variant={fitLabelTone(analysis.fitLabel)}>
              {analysis.fitLabel}
            </Badge>
          </div>
          <div
            className="mt-2 h-2 w-full overflow-hidden rounded-full bg-muted"
            role="img"
            aria-label={`Fit score ${analysis.fitScore} out of 100, ${analysis.fitLabel}`}
          >
            <div
              className={`h-full rounded-full ${SCORE_BAR[tone]}`}
              style={{ width: `${analysis.fitScore}%` }}
            />
          </div>
        </div>

        <div>
          <p className="text-xs font-medium tracking-wide text-muted-foreground uppercase">
            Confidence
          </p>
          <div className="mt-1 flex items-baseline gap-1.5">
            <span className="text-3xl font-semibold tabular-nums">
              {formatConfidence(analysis.confidence)}
            </span>
          </div>
          <p className="mt-2 text-xs text-muted-foreground">
            How much of the assessment is supported by the available data.
          </p>
        </div>
      </div>

      <div>
        <h3 className="text-sm font-medium">Summary</h3>
        <p className="mt-2 text-sm leading-relaxed text-muted-foreground break-words">
          {analysis.summary}
        </p>
      </div>

      {/* Evidence: statements the model read off the supplied fields. */}
      {evidence.length > 0 ? (
        <div>
          <div className="flex flex-wrap items-center gap-2">
            <h3 className="text-sm font-medium">Why this lead fits</h3>
            <Badge variant="outline">From your data</Badge>
          </div>
          <ul className="mt-2 space-y-2">
            {evidence.map((signal) => (
              <li key={signal} className="flex gap-2 text-sm">
                <Check
                  className="mt-0.5 size-4 shrink-0 text-success"
                  aria-hidden="true"
                />
                <span className="min-w-0 break-words">{signal}</span>
              </li>
            ))}
          </ul>
        </div>
      ) : null}

      {/* Inference: reasoned to, and labelled as such. */}
      {inferred.length > 0 ? (
        <div>
          <div className="flex flex-wrap items-center gap-2">
            <h3 className="text-sm font-medium">What the AI inferred</h3>
            <Badge variant="info">AI inference</Badge>
          </div>
          <ul className="mt-2 space-y-2">
            {inferred.map((signal) => (
              <li key={signal} className="flex gap-2 text-sm">
                <span
                  className="mt-1.5 size-1.5 shrink-0 rounded-full bg-info"
                  aria-hidden="true"
                />
                <span className="min-w-0 break-words text-muted-foreground">
                  {signal}
                </span>
              </li>
            ))}
          </ul>
        </div>
      ) : null}

      {evidence.length === 0 && inferred.length === 0 ? (
        <p className="text-sm text-muted-foreground">
          No qualifying signals were found.
        </p>
      ) : null}

      <div className="rounded-lg border border-border bg-muted/40 px-4 py-3">
        <h3 className="text-sm font-medium">Recommended action</h3>
        <p className="mt-1 text-sm leading-relaxed break-words">
          {analysis.recommendedAction}
        </p>
      </div>

      {analysis.unknowns.length > 0 ? (
        <div>
          <h3 className="flex items-center gap-1.5 text-sm font-medium">
            <TriangleAlert className="size-4 text-warning" aria-hidden="true" />
            Not established from the available data
          </h3>
          <ul className="mt-2 flex flex-wrap gap-2">
            {analysis.unknowns.map((unknown) => (
              <li key={unknown}>
                <Badge variant="secondary">{unknown}</Badge>
              </li>
            ))}
          </ul>
        </div>
      ) : null}

      <p className="border-t border-border pt-3 text-xs text-muted-foreground">
        {ANALYSIS_NOTICE}
      </p>
    </div>
  );
}
